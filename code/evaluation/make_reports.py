"""Generate code/evaluation/evaluation_report.md and usage_report.md from scored outputs and the usage ledger.

Usage (repository root):
  python code/evaluation/make_reports.py --full-run final_full_v3 \
      [--samples-pred output_samples.csv] [--custom-pred output_custom.csv]
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.stdout.reconfigure(encoding="utf-8")

from ghost.config import CODE_DIR, REPO_ROOT, path as cfg_path, settings  # noqa: E402
from evaluation.score import read_rows, score, split_cases  # noqa: E402

EVAL_DIR = CODE_DIR / "evaluation"


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def metrics_row(name: str, m: dict) -> str:
    return (f"| {name} | {m['cases']} | {pct(m['status_accuracy'])} | {m['step']['precision']:.3f} | "
            f"{m['step']['recall']:.3f} | {m['step']['f1']:.3f} | {m['step_ignoring_evidence']['f1']:.3f} | "
            f"{m['resource']['f1']:.3f} | {pct(m['evidence_accuracy'])} | {pct(m['sequence_accuracy'])} | "
            f"{m['contract_error_rows']} |")


HEADER = ("| split | cases | status acc. | step P | step R | step F1 | step F1 (no evidence) | resource F1 | "
          "evidence acc. | sequence acc. | contract errors |\n|---|---|---|---|---|---|---|---|---|---|---|")


def field_table(m: dict) -> str:
    rows = "\n".join(f"| {k} | {pct(v)} |" for k, v in m["field_accuracy"].items())
    return "| field | position-aligned accuracy |\n|---|---|\n" + rows


def diff_summary(details: list[dict]) -> str:
    c = Counter()
    for d in details:
        for s in d["missing_steps"]:
            c[("missing", s["operation"])] += 1
        for s in d["extra_steps"]:
            c[("extra", s["operation"])] += 1
    if not c:
        return "_No step differences._"
    return "| kind | operation | count |\n|---|---|---|\n" + "\n".join(
        f"| {k} | {op} | {n} |" for (k, op), n in sorted(c.items(), key=lambda x: -x[1]))


def evaluation_report(samples_pred: Path, custom_pred: Path | None) -> str:
    gold = read_rows(REPO_ROOT / "dataset" / "sample_output.csv")
    pred = read_rows(samples_pred)
    splits = split_cases(gold)
    res = {k: score(pred, gold, v) for k, v in splits.items()}
    m_all, d_all = res["all"]
    out = [
        "# Evaluation report - Ghost Data Still Exists",
        "",
        "Generated by `code/evaluation/make_reports.py` from `code/evaluation/score.py` "
        "(metric definitions are documented at the top of that file; the official grader formula is not published).",
        "",
        "## 1. Accuracy on the 32 public samples",
        "",
        "Labelled data: `dataset/sample_output.csv`. Split: stratified by status; within each status (case_id order) "
        "cases alternate dev / held-out (16 / 16; COMPLETE 5/5, INCOMPLETE 11/11).",
        "",
        HEADER,
        metrics_row("all", m_all),
        metrics_row("dev", res["dev"][0]),
        metrics_row("held-out", res["holdout"][0]),
        "",
        "- **Case-level accuracy** = status accuracy; **row-level** = step precision / recall / F1 over full steps "
        "(phase, system_id, resource_id, operation, state, evidence_id);",
        "- **field-level** = position-aligned per-field accuracy below; **sequence accuracy** = the entire ordered "
        "step list (and status) matches exactly.",
        "",
        "### Field-level accuracy (all samples)",
        "",
        field_table(m_all),
        "",
        "### Remaining step differences (all samples)",
        "",
        diff_summary(d_all),
        "",
    ]
    if custom_pred and custom_pred.exists():
        cgold = read_rows(EVAL_DIR / "custom_cases" / "expected.csv")
        cm, cd = score(read_rows(custom_pred), cgold, set(cgold))
        reqs = {r["case_id"]: r for r in csv.DictReader(open(EVAL_DIR / "custom_cases" / "requests.csv",
                                                                encoding="utf-8"))}
        out += [
            "## 2. Participant-created evaluation cases",
            "",
            "Defined in `code/evaluation/custom_cases/` (see its README). Each reuses the evidence of a public sample "
            "and changes one input, so the expected answer is known without organizer data.",
            "",
            "| case | request change | expected | predicted | exact match |",
            "|---|---|---|---|---|",
        ]
        for d in cd:
            r = reqs[d["case_id"]]
            change = ("email " + r["email"]) if r["email"] != r["email"].lower() else r["request_text"][:70] + "..."
            out.append(f"| {d['case_id']} | {change} | {d['status']['gold']} | {d['status']['pred']} | "
                       f"{'yes' if d['sequence_exact'] else 'no'} |")
        out += ["", HEADER, metrics_row("custom", cm), ""]
    out += [
        "## 3. Failures found and improvements made",
        "",
        "Iterations on the samples (all splits), each driven by the per-case diff from `score.py --details`:",
        "",
        "| iteration | change | status acc. | step F1 | cost / 32 cases |",
        "|---|---|---|---|---|",
        "| 1 | first end-to-end run, all agents Haiku 5.5 | 71.9% | 0.764 | $0.26 |",
        "| 2 | intake: deletion-verification follow-ups are deletion requests; separate second-opinion prompt; "
        "snapshot coverage inferred from row systems; INCOMPLETE without findings -> COMPLETE | 96.9% | 0.807 | $0.24 |",
        "| 3 | reviewer/investigator accept the workflow-job primary profile; empty revisions rejected; retained "
        "security audit logs verified PRESENT; support attachments vs messages | 96.9% | 0.897 | $0.23 |",
        "| 4 | invented / image-only ids dropped (ids must exist in participant data; image ids need a known prefix); "
        "findings must cite evidence that observes the resource; case-level retries for network errors | 96.9% | 0.883 | $0.23 |",
        "| 5 | Sonnet 5.5 for investigator + planner (measured) | 100% | 0.914 | $1.33 |",
        "| 6 | reviewer only when the contract guardrail reports issues (the always-on Haiku reviewer forced "
        "revisions in 46% of cases and lowered F1) | 100% | 0.916 | $1.07 |",
        "| 7 (final) | all agents Haiku 5.5, review on issues, Sonnet only as escalation for persistent "
        "contract issues | 100% | 0.913-0.934 | $0.145 |",
        "",
        "Failures that motivated the changes:",
        "",
        "- **Intake false negatives** (5 samples): \"please verify my deletion is complete\" was read as a status "
        "question. The spec reserves NOT_APPLICABLE for access, correction, export, opt-out and other non-deletion "
        "actions; prompt fixed, plus a lexical cross-check with an independent second opinion.",
        "- **Over-cautious status**: the planner returned INCOMPLETE with no findings because it could not prove "
        "unobserved systems were clean. Rule: INCOMPLETE requires an evidenced violation; enforced by the guardrail.",
        "- **Absence evidence missed**: snapshot tables that do not name a system were not treated as covering it; "
        "coverage is now inferred from the rows' resources (gold cites such snapshots).",
        "- **Invented resource ids** (file names, order and ticket numbers): steps on ids that exist in no participant "
        "data are dropped; screenshot records showing a display name are mapped through catalogue aliases "
        "(e.g. `object_19 (delivery_confirmation_19.pdf)`).",
        "- **Unsupported findings**: findings citing an absence snapshot or a workflow claim (remediation-type "
        "activity) are rejected; evidence must observe the resource.",
        "- **Noisy review loop**: an always-on reviewer rejected correct workflow-job links; now runs only when the "
        "contract guardrail reports issues.",
        "- **Empty snapshot used as absence proof** (found by custom case custom_01): a snapshot with no rows at all "
        "was offered as evidence that a record was deleted and outweighed a failover replica that still held it; "
        "empty snapshots no longer count as absence evidence (custom cases went from 3/4 to 4/4 exact).",
        "- **Escalation regression** (full run, case_61): the stronger model replaced a valid plan with an empty one; "
        "escalated plans are now accepted only when they are not worse.",
        "",
        "Known remaining limitations (documented, not hidden):",
        "",
        "- Concurrent workflow jobs with identical timing make some identifier-less resources (primary profiles, "
        "anonymised analytics records) genuinely ambiguous; ambiguous follow-ups are excluded (measured: including "
        "them added more false positives than true positives).",
        "- A few sample gold resources appear in no participant-visible data and cannot be recovered without guessing.",
        "- Category judgement for borderline records (e.g. analytics contact rows keyed by a historical hash) "
        "remains model-dependent.",
        "",
    ]
    return "\n".join(out)


def usage_report(run_id: str) -> str:
    ledger = cfg_path("cache") / "usage" / f"{run_id}.jsonl"
    rows = [json.loads(l) for l in ledger.read_text(encoding="utf-8").splitlines()]
    pricing = settings()["pricing"]
    n_requests = sum(1 for _ in csv.DictReader(open(REPO_ROOT / "output.csv", encoding="utf-8")))
    statuses = Counter(r["deletion_status"] for r in csv.DictReader(open(REPO_ROOT / "output.csv", encoding="utf-8")))

    def cost(r):
        p = pricing.get(r["model"]) or pricing.get(r["requested_model"])
        return (r["input_tokens"] * p["input"] + r["output_tokens"] * p["output"]
                + r["cache_read_input_tokens"] * p["input"] * pricing["cache_read_multiplier"]
                + r["cache_creation_input_tokens"] * p["input"] * pricing["cache_write_multiplier"]) / 1e6

    per_model = defaultdict(lambda: Counter())
    per_agent = defaultdict(lambda: Counter())
    for r in rows:
        for bucket in (per_model[r["model"]], per_agent[(r["agent"], r["model"])]):
            bucket["calls"] += 1
            bucket["served_from_cache"] += r["cached"]
            for k in ("input_tokens", "output_tokens", "cache_read_input_tokens", "cache_creation_input_tokens"):
                bucket[k] += r[k]
            bucket["cost_milli"] += cost(r) * 1000
    tot = Counter()
    for m in per_model.values():
        tot.update(m)

    def line(name, c):
        total_tokens = c["input_tokens"] + c["output_tokens"] + c["cache_read_input_tokens"] + c["cache_creation_input_tokens"]
        return (f"| {name} | {c['calls']} | {c['input_tokens']:,} | {c['cache_read_input_tokens']:,} | "
                f"{c['cache_creation_input_tokens']:,} | {c['output_tokens']:,} | {total_tokens:,} | "
                f"{total_tokens / n_requests:,.0f} | ${c['cost_milli'] / 1000:.2f} | ${c['cost_milli'] / 1000 / n_requests:.4f} |")

    head = ("| model | calls | input tokens | cache-read input | cache-write input | output tokens | total tokens | "
            "avg tokens / request | est. cost | est. cost / request |\n|---|---|---|---|---|---|---|---|---|---|")
    agent_rows = "\n".join(
        f"| {a} | {m} | {c['calls']} | {c['input_tokens'] + c['cache_read_input_tokens'] + c['cache_creation_input_tokens']:,} | "
        f"{c['output_tokens']:,} | ${c['cost_milli'] / 1000:.3f} |" for (a, m), c in sorted(per_agent.items()))
    price_rows = "\n".join(f"| {m} | ${p['input']:.2f} | ${p['output']:.2f} |" for m, p in pricing.items()
                           if isinstance(p, dict))
    return "\n".join([
        "# Usage report - final full-dataset run",
        "",
        f"Run id `{run_id}` produced the submitted `output.csv` ({n_requests} requests: "
        + ", ".join(f"{k} {v}" for k, v in sorted(statuses.items())) + ").",
        "Generated by `code/evaluation/make_reports.py` from the per-call usage ledger written by `code/ghost/llm.py` "
        "(one row per model call with the API-reported token usage).",
        "",
        "Provider: **Anthropic** (Claude API, Python SDK). Models: **Claude Haiku 5.5** (`claude-haiku-5-5`) for every "
        "agent; **Claude Sonnet 5.5** (`claude-sonnet-5-5`) configured only as escalation for cases whose plan still "
        "violates the contract after review. Responses are cached on disk keyed by the exact request, so a call that "
        "was served from the cache during this run is reported with the usage of the original API call that produced it "
        "(the totals below are the full cost of producing the output).",
        "",
        "## Per-model and overall totals",
        "",
        head,
        *[line(m, c) for m, c in sorted(per_model.items())],
        line("**overall**", tot),
        "",
        f"Model calls served from the local cache during this run: {tot['served_from_cache']} of {tot['calls']}.",
        "",
        "## Per-agent breakdown",
        "",
        "| agent | model | calls | input tokens (incl. cache) | output tokens | est. cost |",
        "|---|---|---|---|---|---|",
        agent_rows,
        "",
        "## Pricing used (USD per 1M tokens, Anthropic list price)",
        "",
        "| model | input | output |",
        "|---|---|---|",
        price_rows,
        "",
        f"Cache reads are priced at {pricing['cache_read_multiplier']}x input, cache writes at "
        f"{pricing['cache_write_multiplier']}x input.",
        "",
        "## Cost optimisation history",
        "",
        "The first full-run attempt (Sonnet 5.5 investigator and planner, reviewer on every case) was projected at "
        "about $22 for 518 requests and was stopped. Measured on the samples, all-Haiku with the reviewer only on "
        "contract issues matched or beat it (status 100%, step F1 0.913-0.934) at $0.145 per 32 cases, about 10x "
        "cheaper. No API keys or credentials are included in this report.",
        "",
    ])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--full-run", required=True, help="run id of the full-dataset run that produced output.csv")
    ap.add_argument("--samples-pred", default="output_samples.csv")
    ap.add_argument("--custom-pred", default="output_custom.csv")
    a = ap.parse_args()
    (EVAL_DIR / "evaluation_report.md").write_text(
        evaluation_report(REPO_ROOT / a.samples_pred, REPO_ROOT / a.custom_pred), encoding="utf-8")
    (EVAL_DIR / "usage_report.md").write_text(usage_report(a.full_run), encoding="utf-8")
    print("wrote", EVAL_DIR / "evaluation_report.md")
    print("wrote", EVAL_DIR / "usage_report.md")


if __name__ == "__main__":
    main()
